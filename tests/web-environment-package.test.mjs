import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { prepareRelease } from "../server/release.mjs";
import { sourceDigest, buildMetadata, verifyEnvironmentSource } from "../deploy/environments/metadata.mjs";
import { packageEnvironment } from "../deploy/environments/package.mjs";

test("environment package binds accepted source, normalized digest, and isolated runtime", async (t) => {
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), "environment-package-"));
  t.after(() => fs.rmSync(parent, { recursive: true, force: true }));
  const release = path.join(parent, "release");
  await prepareRelease(release, { install: false });
  const manifestPath = path.join(release, "web-release.json");
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  manifest.accepted = true;
  manifest.acceptance = { ok: true, scope: "isolated-test-fixture" };
  fs.writeFileSync(manifestPath, JSON.stringify(manifest));
  const runtime = path.join(parent, "runtime");
  fs.mkdirSync(path.join(runtime, "node"), { recursive: true });
  fs.writeFileSync(path.join(runtime, "node", "node.exe"), "fixture-runtime");
  fs.writeFileSync(path.join(runtime, "LICENSE"), "test license");
  fs.mkdirSync(path.join(release, "node_modules", "fixture-dependency"), { recursive: true });
  fs.writeFileSync(path.join(release, "node_modules", "fixture-dependency", "index.js"), "export default 1;\n");
  const vendor = path.join(release, "node_modules", "vendor-package");
  fs.mkdirSync(path.join(vendor, "test", "fixtures"), { recursive: true });
  fs.mkdirSync(path.join(vendor, "lib"), { recursive: true });
  fs.writeFileSync(path.join(vendor, "package.json"), JSON.stringify({ name: "vendor-package", version: "1.0.0" }));
  fs.writeFileSync(path.join(vendor, "test", "fixtures", "fastify.key"), "public vendor test fixture key");
  fs.writeFileSync(path.join(vendor, "lib", "runtime.js"), "export const runtime = true;\n");
  for (const packageDir of [path.join(release, "node_modules", "test"), path.join(release, "node_modules", "@scope", "test")]) {
    fs.mkdirSync(packageDir, { recursive: true });
    fs.writeFileSync(path.join(packageDir, "package.json"), JSON.stringify({ name: "test", version: "1.0.0" }));
  }
  const unlistedFile = path.join(release, "server", "unlisted.js");
  fs.writeFileSync(unlistedFile, "export const unexpected = true;\n");
  assert.throws(() => packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: path.join(parent, "unlisted-attempt"), commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" }), /未登记文件/);
  fs.rmSync(unlistedFile);
  const outsideSecret = path.join(parent, "outside.key");
  fs.writeFileSync(outsideSecret, "secret");
  fs.writeFileSync(path.join(release, ".env"), "SECRET=fixture\n");
  assert.throws(() => packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: path.join(parent, "leak-attempt"), commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" }), /未登记文件/);
  fs.rmSync(path.join(release, ".env"));
  fs.mkdirSync(path.join(runtime, "internal-links"));
  fs.symlinkSync("../node/node.exe", path.join(runtime, "internal-links", "node.exe"), "file");

  const digest = sourceDigest(release);
  assert.match(digest, /^[a-f0-9]{64}$/);
  const metadata = buildMetadata({ releaseRoot: release, target: "windows-x64", commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" });
  assert.equal(metadata.commonSourceSHA256, digest);
  assert.equal(verifyEnvironmentSource(release, metadata), digest);
  assert.throws(() => verifyEnvironmentSource(release, { ...metadata, commonSourceSHA256: "0".repeat(64) }), /不符/);
  const output = path.join(parent, "package");
  packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: output, commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" });
  assert(fs.existsSync(path.join(output, "erp", "web-release.json")));
  assert(fs.existsSync(path.join(output, "runtime", "node", "node.exe")));
  assert.equal(fs.readFileSync(path.join(output, "erp", "node_modules", "fixture-dependency", "index.js"), "utf8"), "export default 1;\n");
  assert.equal(fs.existsSync(path.join(output, "erp", "node_modules", "vendor-package", "test")), false);
  assert.equal(fs.readFileSync(path.join(output, "erp", "node_modules", "vendor-package", "lib", "runtime.js"), "utf8"), "export const runtime = true;\n");
  assert(fs.existsSync(path.join(output, "erp", "node_modules", "test", "package.json")));
  assert(fs.existsSync(path.join(output, "erp", "node_modules", "@scope", "test", "package.json")));
  assert(fs.lstatSync(path.join(output, "runtime", "internal-links", "node.exe")).isSymbolicLink());
  assert.equal(fs.readlinkSync(path.join(output, "runtime", "internal-links", "node.exe")).replace(/\\/g, "/"), "../node/node.exe");
  assert.equal(JSON.parse(fs.readFileSync(path.join(output, "environment-build.json"))).commonSourceSHA256, digest);
  assert.throws(() => packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: output, commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" }), /新目录|存在/);
  const outsideLink = path.join(runtime, "outside.key");
  fs.symlinkSync("../outside.key", outsideLink, "file");
  assert.throws(() => packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: path.join(parent, "escape-attempt"), commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" }), /树外链接/);
  fs.rmSync(outsideLink);
  fs.writeFileSync(path.join(vendor, "private.key"), "private key");
  assert.throws(() => packageEnvironment({ target: "windows-x64", releaseRoot: release, runtimeRoot: runtime, outputRoot: path.join(parent, "private-key-attempt"), commit: "a".repeat(40), runId: "123", nodeVersion: "24.22.2" }), /凭据/);

  fs.appendFileSync(path.join(release, manifest.files[0].path), "changed");
  assert.throws(() => sourceDigest(release), /变化/);
  manifest.accepted = false;
  fs.writeFileSync(manifestPath, JSON.stringify(manifest));
  assert.throws(() => sourceDigest(release), /验收/);
});

test("source digest is stable across CRLF text and excludes generated package lock", async (t) => {
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), "environment-digest-"));
  t.after(() => fs.rmSync(parent, { recursive: true, force: true }));
  const release = path.join(parent, "release");
  await prepareRelease(release, { install: false });
  const mf = path.join(release, "web-release.json");
  const m = JSON.parse(fs.readFileSync(mf, "utf8"));
  m.accepted = true;
  m.acceptance = { ok: true };
  fs.writeFileSync(mf, JSON.stringify(m));
  const file = path.join(release, m.files.find((x) => x.path.endsWith(".mjs")).path);
  const before = sourceDigest(release);
  const relative = path.relative(release, file).split(path.sep).join("/");
  const item = m.files.find((x) => x.path === relative);
  const data = fs.readFileSync(file, "utf8").replace(/\r\n?/g, "\n");
  fs.writeFileSync(file, data.replace(/\n/g, "\r\n"));
  const digest = await import("node:crypto").then(({ createHash }) => createHash("sha256").update(fs.readFileSync(file)).digest("hex"));
  item.sha256 = digest;
  fs.writeFileSync(mf, JSON.stringify(m));
  assert.equal(sourceDigest(release), before);
  const scriptRelative = "server/hash-boundary.ps1";
  const scriptPath = path.join(release, scriptRelative);
  fs.writeFileSync(scriptPath, "param()\nWrite-Output 'ok'\n");
  const makeHash = (bytes) => import("node:crypto").then(({ createHash }) => createHash("sha256").update(bytes).digest("hex"));
  m.files.push({ path: scriptRelative, sha256: await makeHash(fs.readFileSync(scriptPath)) });
  fs.writeFileSync(mf, JSON.stringify(m));
  const withLf = sourceDigest(release);
  fs.writeFileSync(scriptPath, "param()\r\nWrite-Output 'ok'\r\n");
  m.files.at(-1).sha256 = await makeHash(fs.readFileSync(scriptPath));
  fs.writeFileSync(mf, JSON.stringify(m));
  assert.equal(sourceDigest(release), withLf, ".ps1 CRLF and LF must share the common source digest");
  fs.writeFileSync(path.join(release, "package-lock.json"), "generated lock");
  assert.equal(sourceDigest(release), withLf);
});
