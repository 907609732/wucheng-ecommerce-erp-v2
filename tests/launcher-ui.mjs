import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {_electron as electron} from 'playwright';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'lingtu-launcher-ui-'));
const registry = path.join(root, 'registry.json');
fs.writeFileSync(registry, JSON.stringify(Object.fromEntries(['warehouse','purchase','sales','overview','exporter'].map(id => [id, {
  managed: true, root: path.join(root, id), dataDir: path.join(root, 'data', id), exe: path.join(root, id, 'missing.exe')
}]))));
const env = {...process.env, LINGTU_REGISTRY_PATH: registry, LINGTU_ISOLATED_TEST:'1', LINGTU_SKIP_BUNDLED_ACTIVATION:'1'}; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({executablePath: path.resolve(process.env.LAUNCHER_TEST_EXE || 'node_modules/electron/dist/electron.exe'),
  args: [...(process.env.LAUNCHER_TEST_EXE ? [] : [path.resolve('desktop/launcher')]), '--user-data-dir=' + root], env});
const errors = [];
try {
  const page = await app.firstWindow();
  page.on('pageerror', e => errors.push(e.message));
  await page.locator('#personnelBoss').click();
  await page.locator('#cards button').first().waitFor();
  assert.equal(await page.title(),'五成电子商务工作台');
  assert.equal(await page.locator('.brand strong').textContent(),'五成电子商务工作台');
  assert.equal(await page.locator('#cards article').count(), 4);
  assert.deepEqual(await page.locator('#cards .card h3').allTextContents(), ['菜鸟云仓同步','经营收支总览','销售台','采购台']);
  assert.deepEqual(await page.locator('.workflowHeading h2').allTextContents(), ['每天使用','每月填写']);
  assert.match(await page.locator('.monthly .workflowHeading p').textContent(), /每月 15 号/);
  const daily=await page.locator('.daily .card').last().boundingBox(),monthly=await page.locator('.monthly .card').first().boundingBox();
  assert.ok(daily.y+daily.height<monthly.y);
  const overview=await page.locator('[data-module=overview]').boundingBox(),warehouse=await page.locator('[data-module=warehouse]').boundingBox();
  assert.ok(warehouse.y+warehouse.height<overview.y);
  assert.deepEqual(await page.locator('.daily .card h3').allTextContents(), ['菜鸟云仓同步']);
  assert.deepEqual(await page.locator('.monthly .card h3').allTextContents(), ['经营收支总览','销售台','采购台']);
  assert.doesNotMatch(await page.locator('[data-module=sales] p').textContent(),/经营收支总览/);
  const sales=await page.locator('[data-module=sales]').boundingBox(),purchase=await page.locator('[data-module=purchase]').boundingBox();
  assert.equal(sales.y,purchase.y);assert.ok(sales.x<purchase.x);
  assert.ok(overview.y+overview.height<sales.y);assert.ok(overview.width>sales.width);
  assert.deepEqual(await page.locator('#cards button').allTextContents(), ['需要修复','需要修复','需要修复','需要修复']);
  assert.equal(await page.locator('#cards button:disabled').count(),4,'Missing suite cannot offer per-feature downloads');
  assert.equal(await page.locator('#settings').isVisible(),true);
  assert.equal(await page.locator('#help').isVisible(),false);
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='五成电子商务工作台').isMenuBarVisible()),false);
  await page.locator('#settings').click();
  await page.locator('#settingsPanel').waitFor({state:'visible'});
  assert.equal(await page.locator('#hostUpdate').isVisible(),true);
  assert.equal(await page.locator('#advancedSettings').getAttribute('open'),null);
  assert.equal(await page.locator('#permissionSettings').isVisible(),true,'Boss can find employee permissions without expanding advanced settings');
  assert.equal(await page.locator('#permissionsOpen').isEnabled(),true);
  await page.locator('#permissionsOpen').click();
  await page.locator('#permissionsDialog').waitFor({state:'visible'});
  await page.locator('#permissionClose').click();
  await page.locator('#personnelChange').click();
  await page.locator('#personnelEmployee').click();
  await page.locator('#settings').click();
  assert.equal(await page.locator('#permissionSettings').isVisible(),false,'Employee cannot manage member permissions after connection refresh');
  const denied=await page.evaluate(()=>window.launcher.permissions().then(()=>false,()=>true));
  assert.equal(denied,true,'Main process also denies employee permission reads');
  await page.locator('#personnelChange').click();
  await page.locator('#personnelBoss').click();
  await page.locator('#settings').click();
  assert.ok(await page.locator('#moduleList article').count()>=5);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='五成电子商务工作台').webContents.send('desks:navigate',{id:'help'}));
  await page.locator('#helpDialog').waitFor({state:'visible'});
  await page.locator('#closeHelp').click();
  await page.locator('#home').click();
  await page.locator('#homePanel').waitFor({state:'visible'});
  await page.locator('#logs').click();await page.locator('#logsPanel').waitFor({state:'visible'});
  await page.evaluate(()=>window.launcher.reportDiagnostic({level:'error',text:'DIAGNOSTIC-FIXTURE <img src=x onerror=alert(1)> password="fixture secret phrase"'}));
  await page.locator('#logLevel').selectOption('error');await page.locator('#logQuery').fill('DIAGNOSTIC-FIXTURE');await page.locator('#logRefresh').click();
  await page.waitForFunction(()=>document.querySelector('#logEntries')?.textContent.includes('DIAGNOSTIC-FIXTURE'));
  assert.equal(await page.locator('#logEntries img').count(),0);assert.ok(!(await page.locator('#logEntries').textContent()).includes('fixture secret phrase'));
  const reportPath=path.join(root,'diagnostic-export.json');
  await app.evaluate(({dialog},destination)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:destination});},reportPath);
  const exported=await page.evaluate(()=>window.launcher.exportLogs());assert.equal(exported.exported,true);
  const report=JSON.parse(fs.readFileSync(reportPath,'utf8'));assert.equal(report.format,'lingtu-diagnostics/v1');assert.ok(!JSON.stringify(report).includes('fixture secret phrase'));
  await page.locator('#logsBack').click();await page.locator('#homePanel').waitFor({state:'visible'});

  fs.mkdirSync('dist/module-verification', {recursive:true});
  await page.screenshot({path:'dist/module-verification/launcher-first-install.png'});
  assert.equal(await page.locator('#settings').isVisible(),true);
  assert.equal(await page.locator('#help').isVisible(),false);
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='五成电子商务工作台').isMenuBarVisible()),false);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.getTitle()==='五成电子商务工作台').webContents.send('desks:navigate',{id:'settings'}));await page.locator('#advancedSettings > summary').click();
  assert.equal(await page.locator('#startAtLogin').isChecked(),false,'New profiles do not enable Windows startup');
  assert.equal(await page.locator('#moduleList button').filter({hasText:'卸载'}).count(),0);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().length),1);
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isVisible()),false,'X hides to tray');
  assert.deepEqual(errors, []);
  assert.ok(!fs.existsSync(path.join(root, 'workspace', 'data', 'erp.sqlite')));
  console.log(JSON.stringify({ok:true, homeEntries:4, overviewFirstMonthly:true, noBusinessDatabaseCreated:true, rendererErrors:errors}));
} finally { await app.close(); }
