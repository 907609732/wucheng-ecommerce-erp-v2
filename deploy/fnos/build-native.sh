#!/bin/bash
# Complete official Native FPK. CI/build machine only; never run on production NAS.
set -euo pipefail
export PATH=/usr/sbin:/usr/bin:/sbin:/bin
helper=$(cd -- "$(dirname -- "$0")" && pwd)
repo=$(cd "$helper/../.." && pwd)
source "$helper/native-inputs.env"
[[ $(id -u) = 0 && $(uname -m) = x86_64 ]] || { echo 'Build requires ephemeral Debian 12 amd64 root (not NAS).' >&2; exit 1; }
source /etc/os-release
[[ $ID = debian && $VERSION_ID = 12 ]] || { echo 'Build requires Debian bookworm/glibc 2.36.' >&2; exit 1; }
[[ -x /usr/bin/python3 ]] || { echo 'Build prerequisite: install official Debian python3.' >&2; exit 1; }
[[ $(getconf GNU_LIBC_VERSION) = 'glibc 2.36' ]]
out=$(realpath -m -- "${1:-/tmp/wuchengerp-native-output}")
case "$out/" in "$repo/"*) echo 'Output must be outside source tree.' >&2; exit 1;; esac
[[ ! -e $out ]] || { echo 'Output must be a new directory.' >&2; exit 1; }
mkdir -p "$out"; work=$(mktemp -d "${ERP_BUILD_WORK_ROOT:-/tmp}/erp.XXXXXXXX")
finish() {
 local result=$?
 if [[ $result != 0 ]]; then
  set +e
  [[ ! -d "$work/smoke-evidence" ]] || cp -a "$work/smoke-evidence" "$out/smoke-failure-evidence"
  if [[ -d "$work/diag-volume/@wuchengerpdiag-data" ]]; then
   mkdir -p "$out/diagnostic-failure-evidence"
   for evidence in "$work/diag-volume/@wuchengerpdiag-data"/run-*/evidence; do
    [[ ! -d $evidence ]] || cp -a "$evidence" "$out/diagnostic-failure-evidence/$(basename "$(dirname "$evidence")")"
   done
  fi
 fi
 exit "$result"
}
trap finish EXIT
printf '%s\n' "$work" > "$out/BUILD-WORKDIR.txt"
mkdir -p "$work/downloads" "$work/sources" "$work/stage/wuchengerp/app/runtime"
stage="$work/stage/wuchengerp"; runtime="$stage/app/runtime"
fetch() { curl --fail --location --proto '=https' --tlsv1.2 --retry 3 --output "$3" "$1"; printf '%s  %s\n' "$2" "$3" | sha256sum --check --strict; }
fetch "https://nodejs.org/dist/v$NODE_VERSION/node-v$NODE_VERSION-linux-x64.tar.xz" "$NODE_SHA256" "$work/downloads/node.tar.xz"
curl --fail --location --proto '=https' --output "$work/downloads/SHASUMS256.txt" "https://nodejs.org/dist/v$NODE_VERSION/SHASUMS256.txt"
grep -Fx "$NODE_SHA256  node-v$NODE_VERSION-linux-x64.tar.xz" "$work/downloads/SHASUMS256.txt"
mkdir -p "$runtime/node"; tar -xJf "$work/downloads/node.tar.xz" --strip-components=1 -C "$runtime/node"
export PATH="$runtime/node/bin:$PATH"
export PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD=1 NPM_CONFIG_AUDIT=false NPM_CONFIG_FUND=false
fetch "https://static2.fnnas.com/fnpack/fnpack-$FNPACK_VERSION-linux-amd64" "$FNPACK_SHA256" "$work/downloads/fnpack"
chmod 755 "$work/downloads/fnpack"
"$work/downloads/fnpack" --help | tee "$out/fnpack-help.txt"
grep -q '1.2.3' "$out/fnpack-help.txt"
fetch "https://codeload.github.com/novnc/noVNC/tar.gz/refs/tags/v$NOVNC_VERSION" "$NOVNC_SHA256" "$work/sources/noVNC-v$NOVNC_VERSION.tar.gz"
mkdir -p "$runtime/novnc"; tar -xzf "$work/sources/noVNC-v$NOVNC_VERSION.tar.gz" --strip-components=1 -C "$runtime/novnc"
rm -rf "$runtime/novnc/.github" "$runtime/novnc/tests"
# Explicit metadata allowlist, never a deployed app/data folder.
for relative in manifest config/privilege config/resource app/ui/config; do install -D -m644 "$helper/wuchengerp/$relative" "$stage/$relative"; done
# fnpack itself duplicates exactly these static files into app/config. Stage them
# explicitly before snapshots so every generated byte remains an exact match.
for relative in config/privilege config/resource; do install -D -m644 "$stage/$relative" "$stage/app/$relative"; done
for folder in cmd wizard; do
 while IFS= read -r relative; do
  file="$repo/$relative"
  [[ -f $file && ! -L $file ]] || { echo 'Linked/nonfile package metadata refused.' >&2; exit 1; }
  install -D -m755 "$file" "$stage/$folder/$(basename "$file")"
 done < <(git -C "$repo" ls-files "deploy/fnos/wuchengerp/$folder/")
done
for p in ICON.PNG ICON_256.PNG app/ui/images/icon_64.png app/ui/images/icon_256.png; do install -D -m644 "$repo/shared/ui/loading-logo.png" "$stage/$p"; done
bash "$helper/prepare-native-runtime.sh" "$runtime" "$work"
# Existing accepted-release builder installs production Linux dependencies.
cd "$repo"
export npm_execpath="$runtime/node/lib/node_modules/npm/bin/npm-cli.js"
node server/release.mjs "$stage/app/erp"
version=$("$runtime/node/bin/node" -e "process.stdout.write(JSON.parse(require('node:fs').readFileSync(process.argv[1],'utf8')).version)" "$stage/app/erp/package.json")
[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo 'Accepted ERP package.json version is invalid.' >&2; exit 1; }
sed -i -E "s/^version=.*/version=$version/" "$stage/manifest"
grep -Fx "version=$version" "$stage/manifest" >/dev/null || { echo 'fnOS manifest version did not match accepted ERP.' >&2; exit 1; }
cp "$work/debian-packages.json" "$out/debian-packages.json"
cp "$work/xvfb-meson-log.txt" "$out/xvfb-meson-log.txt"
cp "$helper/native-inputs.env" "$out/INPUTS.env"
cp -a "$work/diagnostic" "$out/diagnostic-xvfb"
# Real package-user checks. This canonical path exists only in disposable CI.
useradd --no-create-home --uid 23001 erpbuild
[[ ! -e $(getent passwd erpbuild | cut -d: -f6) ]]
runuser -u erpbuild -- unshare --user --map-root-user true
mkdir -p /var/apps/wuchengerp
ln -s "$stage/app" /var/apps/wuchengerp/target
chmod 755 "$work"
chown erpbuild:erpbuild "$stage/app"
mkdir -p "$work/fixture" "$work/smoke-evidence"; chown erpbuild:erpbuild "$work/fixture" "$work/smoke-evidence"
# Deliberately populated desktop host, in this disposable builder only. Normal
# and diagnostic smoke inherit hostile discovery paths; runtime must replace them.
apt-get install -y --no-install-recommends mesa-vulkan-drivers
for file in /usr/lib/x86_64-linux-gnu/gio/modules/libdconfsettings.so /usr/lib/x86_64-linux-gnu/libnss_mymachines.so.2 /usr/lib/x86_64-linux-gnu/libnss_mdns4_minimal.so.2 /usr/lib/x86_64-linux-gnu/libvulkan_intel.so /usr/lib/x86_64-linux-gnu/libvulkan_radeon.so /usr/lib/x86_64-linux-gnu/libva.so.2 /usr/lib/x86_64-linux-gnu/libva-drm.so.2; do
 [[ -f $file ]]; printf '%s\n' "$file" >> "$out/host-library-fixture.txt"
done
export GIO_MODULE_DIR=/usr/lib/x86_64-linux-gnu/gio/modules GIO_EXTRA_MODULES=/usr/lib/x86_64-linux-gnu/gio/modules
export VK_DRIVER_FILES=/usr/share/vulkan/icd.d VK_ICD_FILENAMES=/usr/share/vulkan/icd.d VK_ADD_DRIVER_FILES=/usr/share/vulkan/icd.d
export VK_LAYER_PATH=/usr/share/vulkan/explicit_layer.d VK_IMPLICIT_LAYER_PATH=/usr/share/vulkan/implicit_layer.d
export LIBVA_DRIVERS_PATH=/usr/lib/x86_64-linux-gnu/dri
# Force actual libc NSS lookups without changing global nsswitch or depending
# on DNS service order. Audit every initialized dependency with the SAME policy.
runuser -u erpbuild -- "$runtime/node/bin/node" --input-type=module - "$runtime" "$helper" "$work/smoke-evidence" <<'JS'
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
const [runtime,helper,evidence]=process.argv.slice(2);
const {isAllowedRuntimeLibrary}=await import(pathToFileURL(path.join(helper,'smoke-checks.mjs')));
const libs=['usr/lib/x86_64-linux-gnu','lib/x86_64-linux-gnu','usr/lib','lib'].map(p=>path.join(runtime,'sysroot',p)).join(':');
for(const service of ['mymachines','mdns4_minimal']){
 const result=spawnSync('/usr/bin/getent',['-s',service,'hosts','erp-closure-fixture.invalid'],{env:{...process.env,LD_LIBRARY_PATH:libs,LD_DEBUG:'libs'},encoding:'utf8',timeout:10000});
 fs.writeFileSync(path.join(evidence,'nss-'+service+'-loader.log'),result.stderr||'');
 assert(!result.error,result.error?.message);assert([0,2].includes(result.status),'NSS lookup failed to execute: '+result.status);
 const loaded=[...(result.stderr||'').matchAll(/calling init:\s+(\/[^\r\n]+)/g)].map(m=>m[1].trim());
 assert(loaded.some(p=>p.startsWith(runtime+'/')&&path.basename(p)==='libnss_'+service+'.so.2'),'Private NSS plugin was not actually loaded: '+service);
 for(const file of loaded)assert(isAllowedRuntimeLibrary(file,runtime,path.join(path.dirname(runtime),'erp')),'Host NSS dependency: '+file);
}
JS
runuser -u erpbuild -- env PATH="$PATH" LD_LIBRARY_PATH="$runtime/sysroot/usr/lib/x86_64-linux-gnu:$runtime/sysroot/lib/x86_64-linux-gnu:$runtime/sysroot/usr/lib:$runtime/sysroot/lib" "$runtime/node/bin/node" "$helper/smoke-native.mjs" --app-root /var/apps/wuchengerp/target --data-root "$work/fixture/data" --evidence-dir "$work/smoke-evidence" --port-offset 1000
# Chromium's pre-sandbox hook dlopens hardware ICD libraries independently of
# VK_* discovery. Prove that this real polluted-host path loaded private copies.
node --input-type=module - "$work/smoke-evidence/loaded-libraries.json" "$runtime" <<'JS'
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const [file,runtime]=process.argv.slice(2),audit=JSON.parse(fs.readFileSync(file,'utf8'));
for(const name of ['libvulkan_intel.so','libvulkan_radeon.so'])assert(audit.observed.some(p=>p.exe.startsWith(runtime+'/chromium/')&&p.libraries.some(lib=>lib.startsWith(runtime+'/sysroot/')&&path.basename(lib)===name)),'Chromium did not preload private '+name);
JS
strace -f -e trace=%file -o "$out/private-runtime-file-probe.log" runuser -u erpbuild -- env LD_LIBRARY_PATH="$runtime/sysroot/usr/lib/x86_64-linux-gnu:$runtime/sysroot/lib/x86_64-linux-gnu:$runtime/sysroot/usr/lib:$runtime/sysroot/lib" "$runtime/chromium/chrome" --version
cp -a "$work/smoke-evidence" "$out/smoke-evidence"
# Source archives are mandatory before packaging, but expensive transfers must
# not mask early private-runtime failures. License/owner metadata already exists.
node "$helper/collect-native-sources.mjs" "$runtime" "$work" --download-sources
node "$helper/collect-sharp-sources.mjs" "$stage" "$work"
node "$helper/collect-canvas-sources.mjs" "$stage" "$work"
node "$helper/write-native-manifest.mjs" "$stage" "$work"
node "$helper/verify-artifact.mjs" "$stage" | tee "$out/artifact-verification.json"
cp "$stage/app/THIRD-PARTY.json" "$out/THIRD-PARTY.json"
cp "$work/sharp-source-inputs.json" "$out/sharp-source-inputs.json"
cp "$work/canvas-source-inputs.json" "$out/canvas-source-inputs.json"
# Official fnpack normalizes manifest whitespace and adds app.tgz checksum.
# Compare all manifest values separately; every other file/link stays exact.
cp "$stage/manifest" "$out/MANIFEST-SOURCE.txt"
find "$stage" -type f ! -path "$stage/manifest" -printf '%P\n' | LC_ALL=C sort > "$out/PAYLOAD-FILES.txt"
(cd "$stage"; find . -type f ! -path ./manifest -print0 | LC_ALL=C sort -z | xargs -0 sha256sum) > "$out/PAYLOAD-SHA256SUMS.txt"
(cd "$stage"; find . -type l -printf '%P -> %l\n' | LC_ALL=C sort) > "$out/PAYLOAD-SYMLINKS.txt"
# The smoke uses a synthetic data root outside the stage and is never packaged.
node "$helper/verify-artifact.mjs" "$stage"
cd "$out"
"$work/downloads/fnpack" build --directory "$stage"
mapfile -t packages < <(find "$out" -maxdepth 1 -name '*.fpk' -type f)
[[ ${#packages[@]} = 1 ]] || { echo 'Official fnpack did not produce exactly one FPK.' >&2; exit 1; }
mkdir -p "$work/unpacked/app"
tar -xf "${packages[0]}" -C "$work/unpacked"
tar -xzf "$work/unpacked/app.tgz" -C "$work/unpacked/app"
node "$helper/verify-packed-manifest.mjs" "$out/MANIFEST-SOURCE.txt" "$work/unpacked/manifest" "$work/unpacked/app.tgz" > "$out/packed-manifest-verification.json"
rm "$work/unpacked/app.tgz"
node "$helper/verify-artifact.mjs" "$work/unpacked" > "$out/packed-artifact-verification.json"
(cd "$work/unpacked"; sha256sum --check --strict "$out/PAYLOAD-SHA256SUMS.txt" > "$out/packed-payload-checks.log")
diff -u "$out/PAYLOAD-FILES.txt" <(find "$work/unpacked" -type f ! -path "$work/unpacked/manifest" -printf '%P\n' | LC_ALL=C sort)
diff -u "$out/PAYLOAD-SYMLINKS.txt" <(cd "$work/unpacked"; find . -type l -printf '%P -> %l\n' | LC_ALL=C sort)
sha256sum "$(basename "${packages[0]}")" > SHA256SUMS.txt
bash "$helper/build-diagnostic.sh" "$stage" "$work" "$out"
# Sources are separate companions and must stay together with any redistribution.
cp "$stage/app/THIRD-PARTY.json" "$work/sources/"
cp "$helper/THIRD-PARTY.md" "$work/sources/README.md"
mkdir -p "$work/sources/native-build"; cp "$helper/"*.sh "$helper/"*.mjs "$helper/"*.py "$helper/native-inputs.env" "$work/sources/native-build/"
cp "$work/diagnostic/meson-buildoptions.json" "$work/sources/native-build/diag-meson-buildoptions.json"
if [[ ${ERP_BUILD_LINUX:-0} == 1 ]]; then
 mkdir -p "$work/sources/environment-build"
 cp -a "$repo/deploy/environments" "$repo/deploy/linux" "$work/sources/environment-build/"
 mkdir -p "$work/sources/native-build/linux-xvfb"
 cp "$work/linux-xvfb/meson-buildoptions.json" "$work/linux-xvfb/source-provenance.txt" "$work/sources/native-build/linux-xvfb/"
 (cd "$work/sources/native-build/linux-xvfb"; sha256sum meson-buildoptions.json source-provenance.txt > SHA256SUMS.txt)
fi
(cd "$work/sources"; find . -type f -print0 | LC_ALL=C sort -z | xargs -0 sha256sum > "$out/SOURCE-SHA256SUMS.txt")
tar --zstd -cf "$out/wuchengerp-$version-corresponding-source.tar.zst" -C "$work/sources" .
zstd --test "$out/wuchengerp-$version-corresponding-source.tar.zst"
tar --zstd -tf "$out/wuchengerp-$version-corresponding-source.tar.zst" | grep -v '/$' | LC_ALL=C sort > "$out/SOURCE-FILES.txt"
diff -u <(awk '{ print substr($0,67) }' "$out/SOURCE-SHA256SUMS.txt") "$out/SOURCE-FILES.txt"
sha256sum "wuchengerp-$version-corresponding-source.tar.zst" >> SHA256SUMS.txt
printf '%s\n' "version=$version" "commit=$(git -C "$repo" rev-parse HEAD)" "run_id=${GITHUB_RUN_ID:-local}" 'platform=linux/amd64' 'libc=host glibc 2.36' > BUILD-INFO.txt
if [[ ${ERP_BUILD_LINUX:-0} == 1 ]]; then
 [[ -n ${ERP_LINUX_OUTPUT:-} ]] || { echo 'ERP_BUILD_LINUX=1 requires a separate ERP_LINUX_OUTPUT directory.' >&2; exit 1; }
 mapfile -t companions < <(find "$out" -maxdepth 1 -type f -name '*-corresponding-source.tar.zst')
 [[ ${#companions[@]} == 1 ]] || { echo 'Expected exactly one same-run corresponding source archive.' >&2; exit 1; }
 export ERP_FNOS_SOURCE_COMPANION=${companions[0]}
 bash "$repo/deploy/linux/build-environment.sh" "$stage/app/erp" "$runtime" "$work/linux-xvfb" "$ERP_LINUX_OUTPUT"
fi
