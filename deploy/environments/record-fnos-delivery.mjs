import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { buildMetadata } from './metadata.mjs';

const [releaseArg, outputArg] = process.argv.slice(2);
if (!releaseArg || !outputArg) throw new Error('usage: record-fnos-delivery.mjs <native-output/release> <new-fnos-target-dir>');
const releaseOut = path.resolve(releaseArg), out = path.resolve(outputArg);
if (fs.existsSync(out)) throw new Error('fnOS delivery output must be a new directory');
const workLine = fs.readFileSync(path.join(releaseOut, 'BUILD-WORKDIR.txt'), 'utf8').trim();
if (!/^\/build\/erp\.[A-Za-z0-9]+$/.test(workLine)) throw new Error('Unexpected native build work path');
const work = workLine;
const sourceRelease = path.join(work, 'stage/wuchengerp/app/erp');
const app = path.join(work, 'unpacked/app');
const file = (p) => { const s = fs.lstatSync(p); if (!s.isFile() || s.isSymbolicLink() || !fs.statSync(p).size) throw new Error(`Missing/invalid evidence: ${p}`); return p; };
const json = (p) => JSON.parse(fs.readFileSync(file(p), 'utf8').replace(/^\uFEFF/, ''));
const digest = (p) => createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const smokeReports = [
  ['smoke-evidence/acceptance.json', 'main build smoke'],
  ['diagnostic-evidence/acceptance.json', 'diagnostic build smoke'],
  ['clean-runtime-evidence/acceptance.json', 'clean-runtime main smoke'],
  ['clean-diagnostic-evidence/acceptance.json', 'clean-runtime diagnostic smoke'],
];
for (const [relative, label] of smokeReports) {
  const report = json(path.join(releaseOut, relative));
  if (report.ok !== true || report.cleanupComplete !== true || Number(report.successfulStarts) < 2) throw new Error(`${label} did not prove success, cleanup, and at least two starts`);
}
for (const name of ['artifact-verification.json', 'packed-manifest-verification.json', 'packed-artifact-verification.json', 'SHA256SUMS.txt', 'wuchengerpdiag.fpk']) {
  const p = path.join(releaseOut, name);
  file(p);
  if (name.endsWith('.json') && json(p).ok !== true) throw new Error(`${name} did not report successful structural acceptance`);
}
const fpkNames = fs.readdirSync(releaseOut).filter((x) => /^wuchengerp.*\.fpk$/.test(x) && !/diag/i.test(x) && x !== 'wuchengerptrial.fpk');
if (fpkNames.length !== 1) throw new Error('Expected exactly one main fnOS FPK');
const packageName = fpkNames[0], packagePath = file(path.join(releaseOut, packageName));
const sourceName = fs.readdirSync(releaseOut).find((x) => /corresponding-source\.tar\.zst$/.test(x));
if (!sourceName) throw new Error('Missing corresponding-source companion');
const sums = fs.readFileSync(path.join(releaseOut, 'SHA256SUMS.txt'), 'utf8');
for (const p of [packageName, sourceName]) {
  const line = sums.split(/\r?\n/).find((x) => x.endsWith(`  ${p}`));
  if (!line || line.split(/\s+/)[0] !== digest(path.join(releaseOut, p))) throw new Error(`SHA256SUMS mismatch: ${p}`);
}
const packagedNode = path.join(app, 'runtime/node/bin/node');
file(packagedNode);
if (path.resolve(process.execPath) !== packagedNode || process.version !== 'v24.22.2') throw new Error('fnOS receipt must be generated by the packaged Node 24.22.2 runtime');
const metadata = buildMetadata({ releaseRoot: sourceRelease, target: 'fnos-x64', commit: process.env.GITHUB_SHA, runId: process.env.GITHUB_RUN_ID, nodeVersion: '24.22.2' });
const buildInfo = fs.readFileSync(path.join(releaseOut, 'BUILD-INFO.txt'), 'utf8');
if (!buildInfo.includes(`commit=${metadata.commit}`) || !buildInfo.includes(`run_id=${metadata.runId}`)) throw new Error('Native build info does not match current workflow');
fs.mkdirSync(out, { recursive: false });
fs.copyFileSync(packagePath, path.join(out, packageName));
for (const [relative] of smokeReports.concat([
  ['artifact-verification.json'],
  ['packed-manifest-verification.json'],
  ['packed-artifact-verification.json'],
])) {
  const src = file(path.join(releaseOut, relative)), dest = path.join(out, relative);
  fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.copyFileSync(src, dest);
}
fs.writeFileSync(path.join(out, 'environment-build.json'), `${JSON.stringify(metadata, null, 2)}\n`);
const acceptance = { schemaVersion: 1, ok: true, cleanupComplete: true, target: metadata.target, version: metadata.version, commit: metadata.commit, runId: metadata.runId, nodeVersion: metadata.nodeVersion, checks: ['native package acceptance: two synthetic starts, stops and SQLite integrity', 'packed FPK structural and payload verification', 'clean Debian 12 runtime and diagnostic install/stop', 'same-run corresponding source companion and SHA256 verified'] };
fs.writeFileSync(path.join(out, 'environment-acceptance.json'), `${JSON.stringify(acceptance, null, 2)}\n`);
const receipt = { schemaVersion: 1, target: metadata.target, packageFile: packageName, packageSHA256: digest(path.join(out, packageName)), acceptance: { passed: true, evidence: ['environment-acceptance.json', 'smoke-evidence/acceptance.json', 'clean-runtime-evidence/acceptance.json', 'artifact-verification.json', 'packed-manifest-verification.json', 'packed-artifact-verification.json'] } };
fs.writeFileSync(path.join(out, 'environment-receipt.json'), `${JSON.stringify(receipt, null, 2)}\n`);
