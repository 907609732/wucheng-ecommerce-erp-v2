import fs from 'node:fs';
import path from 'node:path';
import {sign, createPrivateKey} from 'node:crypto';
import {parseArgs} from 'node:util';
import {pipeline} from 'node:stream/promises';
import yazl from 'yazl';
import {digest, verifyCatalog} from '../desktop/modules/package-format.mjs';
const {values} = parseArgs({options: {directory: {type: 'string'}, key: {type: 'string'}, 'key-id': {type: 'string'}, 'public-keys': {type: 'string'}}});
if (!values.key || !values['key-id'] || !values['public-keys']) throw Error('Provide --key, --key-id and --public-keys; signing private keys must stay outside repositories');
const directory = path.resolve(values.directory || 'dist/modules');
const keyPath = path.resolve(values.key);
if (keyPath.startsWith(process.cwd() + path.sep)) throw Error('Signing private key must be outside the workspace');
const privateKey = createPrivateKey(fs.readFileSync(keyPath));
if (privateKey.asymmetricKeyType !== 'ed25519') throw Error('An Ed25519 release key is required');
const packages = fs.readdirSync(directory).filter(name => name.endsWith('.descriptor.json'))
  .map(name => JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8')));
for (const p of packages) if (await digest(path.join(directory, p.archive)) !== p.sha256) throw Error('Artifact changed after packaging: ' + p.id);
const payload = Buffer.from(JSON.stringify({schemaVersion: 1, publishedAt: new Date().toISOString(), packages}));
const envelope = {format: 'lingtu-catalog/v1', keyId: values['key-id'], payload: payload.toString('base64'), signature: sign(null, payload, privateKey).toString('base64')};
verifyCatalog(envelope, JSON.parse(fs.readFileSync(values['public-keys'], 'utf8')), {hostVersion: JSON.parse(fs.readFileSync('desktop/launcher/package.json','utf8')).version, platform: 'win32', arch: 'x64'});
const catalog = path.join(directory, 'catalog.json');
fs.writeFileSync(catalog, JSON.stringify(envelope, null, 2));
const zip = new yazl.ZipFile();
zip.addFile(catalog, 'catalog.json');
for (const p of packages) zip.addFile(path.join(directory, p.archive), p.archive);
zip.end();
const bundle = path.join(directory, 'LingtuModules-Complete-Offline.zip');
await pipeline(zip.outputStream, fs.createWriteStream(bundle));
console.log(JSON.stringify({packages: packages.map(p => p.id), bundle, sha256: await digest(bundle)}));
