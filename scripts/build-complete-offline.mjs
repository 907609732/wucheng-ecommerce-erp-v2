import fs from 'node:fs';
import path from 'node:path';
import {pipeline} from 'node:stream/promises';
import yazl from 'yazl';
import {digest} from '../desktop/modules/package-format.mjs';
const directory=path.resolve('dist/launcher-release');
const setup='CloudWarehouseInventorySync-Setup-0.8.0-x64.exe';
const modules=path.resolve('dist/modules/LingtuModules-Complete-Offline.zip');
const readme='灵兔启动台 0.8.0 完整离线安装（Windows x64）\r\n\r\n1. 运行 '+setup+' 安装启动台。\r\n2. 打开「扩展与设置 → 导入离线包」。\r\n3. 选择本目录中的 LingtuModules-Complete-Offline.zip，再选择需要的业务模块。\r\n\r\n包内含五个业务扩展及 Node.js、浏览器组件，无需联网、源码或开发环境。\r\n卸载扩展只删除程序，账本和登录数据保留。已有用户继续使用原数据位置。\r\n保留 modules ZIP 的完整文件内容，安装器会验证官方签名和摘要。\r\n';
const zip=new yazl.ZipFile();
zip.addFile(path.join(directory,setup),setup,{compress:false});
zip.addFile(modules,path.basename(modules),{compress:false});
zip.addBuffer(Buffer.from(readme),'离线安装说明.txt');
zip.end();
const output=path.join(directory,'Lingtu-0.8.0-Complete-Offline-Windows-x64.zip');
await pipeline(zip.outputStream,fs.createWriteStream(output));
const files=fs.readdirSync(directory).filter(n=>/\.(exe|zip|yml|blockmap)$/.test(n)&&n!=='builder-debug.yml');
const manifest=[];
for(const name of files)manifest.push({name,bytes:fs.statSync(path.join(directory,name)).size,sha256:await digest(path.join(directory,name))});
fs.writeFileSync(path.join(directory,'SHA256SUMS.txt'),manifest.map(f=>f.sha256+'  '+f.name).join('\n')+'\n');
fs.writeFileSync('dist/module-verification/delivery-files.json',JSON.stringify(manifest,null,2));
console.log(JSON.stringify({output,bytes:fs.statSync(output).size,sha256:await digest(output)}));
