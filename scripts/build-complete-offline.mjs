import fs from 'node:fs';
import path from 'node:path';
import {pipeline} from 'node:stream/promises';
import yazl from 'yazl';
import {digest} from '../desktop/modules/package-format.mjs';
const directory=path.resolve('dist/launcher-release');
const version=JSON.parse(fs.readFileSync('desktop/launcher/package.json','utf8')).version;
const setup=`CloudWarehouseInventorySync-Setup-${version}-x64.exe`;
const payload=JSON.parse(fs.readFileSync('dist/suite-payload-current.json','utf8'));
const suiteManifest=JSON.parse(fs.readFileSync(path.join(payload.directory,'release-manifest.json'),'utf8'));
if(payload.version!==version||suiteManifest.version!==version||suiteManifest.components.length!==7)throw Error('Complete offline delivery requires the matching full suite build');
const readme='五成电子商务工作台 '+version+' 完整离线安装（Windows x64）\r\n\r\n1. 运行 '+setup+' 完整安装工作台；无需另行下载或导入业务扩展。\r\n2. 本机主服务器保留系统 Tailscale。客户端在统一连接中选择内置私网连接，在官方页面完成授权；管理员核对新设备权限。\r\n3. 旧版账本由受控本机迁移流程备份、核对并切换统一业务数据目录；原登录资料保留认证兼容位置，不使用空账本覆盖。\r\n\r\n安装器已包含五个业务模块、网关、内置连接组件、共享 Node.js 与浏览器，无需源码或开发环境。\r\nTailscale 首次登录及加入私网需要网络，安装与本机业务组件不需再次下载。\r\n卸载程序保留业务数据和登录资料。整套升级在全部组件健康检查通过后开放使用。\r\n';
const zip=new yazl.ZipFile();
zip.addFile(path.join(directory,setup),setup,{compress:false});
zip.addFile(path.join(payload.directory,'release-manifest.json'),'release-manifest.json');
zip.addBuffer(Buffer.from(readme),'离线安装说明.txt');
for(const name of ['workbench-tailscale.md','workbench-tailscale-acceptance.md','workbench-embedded-tailnet.md','workbench-interface-coverage.json',`workbench-unified-${version}.md`,'workbench-agent-interface.md'])
  zip.addFile(path.resolve('docs',name),'文档/'+name);
const acceptance=`workbench-unified-acceptance-${version}.md`;
if(fs.existsSync(path.resolve('docs',acceptance)))zip.addFile(path.resolve('docs',acceptance),'文档/'+acceptance);
zip.addBuffer(Buffer.from('完整安装范围及本机/真实平台/双机验收结果以本次验收报告为准。原有网络授权不因安装套装自动扩大。\r\n'),'验收状态.txt');
zip.end();
const output=path.join(directory,`Lingtu-${version}-Complete-Offline-Windows-x64.zip`);
await pipeline(zip.outputStream,fs.createWriteStream(output));
const currentFiles=new Set([setup,setup+'.blockmap',`Lingtu-${version}-Complete-Offline-Windows-x64.zip`,'latest.yml']);
const files=fs.readdirSync(directory).filter(n=>currentFiles.has(n));
const manifest=[];
for(const name of files)manifest.push({name,bytes:fs.statSync(path.join(directory,name)).size,sha256:await digest(path.join(directory,name))});
fs.writeFileSync(path.join(directory,'SHA256SUMS.txt'),manifest.map(f=>f.sha256+'  '+f.name).join('\n')+'\n');
fs.writeFileSync(path.join(directory,`SHA256SUMS-${version}.txt`),manifest.map(f=>f.sha256+'  '+f.name).join('\n')+'\n');
fs.writeFileSync('dist/module-verification/delivery-files.json',JSON.stringify(manifest,null,2));
console.log(JSON.stringify({output,bytes:fs.statSync(output).size,sha256:await digest(output)}));
