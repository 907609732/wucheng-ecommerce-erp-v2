import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const shared=path.join(root,'desktop/shared');
const names=['loading-screen.css','loading-screen.mjs','loading-screen-auto.mjs'];
for(const id of ['purchase','sales','overview']){
  const target=path.join(root,'apps',id,'public');
  for(const name of names)fs.copyFileSync(path.join(shared,name),path.join(target,name));
  fs.copyFileSync(path.join(root,'desktop/assets/lingtu-icon.png'),path.join(target,'loading-logo.png'));
}
// Remote shells already serve an allowlisted app.css and app.js. Embed the
// same CSS and existing logo without creating additional remote endpoints.
const css=fs.readFileSync(path.join(shared,'loading-screen.css'),'utf8');
const logo='data:image/png;base64,'+fs.readFileSync(path.join(root,'desktop/assets/lingtu-icon.png')).toString('base64');
fs.writeFileSync(path.join(shared,'loading-screen-remote.mjs'),'// Generated by scripts/sync-loading-assets.mjs.\nexport const loadingStyles='+JSON.stringify(css)+';\nexport const loadingLogo='+JSON.stringify(logo)+';\n');
const exporter=path.join(root,'apps/exporter/src/shared');
for(const name of ['loading-screen.css','loading-screen.mjs','loading-screen-remote.mjs'])fs.copyFileSync(path.join(shared,name),path.join(exporter,name));
console.log('Synchronized loading assets for three independent modules and remote shells.');
