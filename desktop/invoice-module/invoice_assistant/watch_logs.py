"""Local, structured diagnostic logs. Never capture raw UI/worker output."""
from contextlib import closing
from datetime import datetime, timedelta, timezone
from pathlib import Path
import platform
import re
import sqlite3
import traceback
import uuid

CN = timezone(timedelta(hours=8))
LEVELS = {"INFO": "信息", "WARNING": "提醒", "ERROR": "错误"}


def safe_text(value):
    text = str(value).replace("\r", " ").replace("\n", " ")
    # Defence in depth; callers must supply business messages, not page bodies,
    # exception strings, credentials, configuration dumps or subprocess stdout.
    text = re.sub(r"https?://\S+", "[链接已隐藏]", text, flags=re.I)
    text = re.sub(r"(?i)\b(?:password|passwd|token|cookie|secret|authorization|api[_-]?key)\b\s*[:=]\s*(?:\"[^\"]*\"|'[^']*'|\S+)", "[授权信息已隐藏]", text)
    text = re.sub(r"(?:密码|验证码|税号|纳税人识别号)\s*[:：=]\s*\S+", "[敏感字段已隐藏]", text)
    text = re.sub(r"\btb\d+\b", "[账号已隐藏]", text, flags=re.I)
    text = re.sub(r"(?<![A-Za-z0-9])(?:[0-9A-Z]{15,20})(?![A-Za-z0-9])", "[标识已隐藏]", text)
    return text[:2000]


def database(root):
    Path(root).mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(Path(root) / "runtime-logs.sqlite3", timeout=15)
    conn.row_factory = sqlite3.Row
    conn.execute("CREATE TABLE IF NOT EXISTS logs(id INTEGER PRIMARY KEY, timestamp TEXT NOT NULL, level TEXT NOT NULL, run_id TEXT NOT NULL, stage TEXT NOT NULL, message TEXT NOT NULL, code TEXT NOT NULL)")
    return conn


def append_log(root, level, stage, message, *, run_id="", code=""):
    if level not in LEVELS:
        raise ValueError("无效日志级别")
    # Task IDs are generated by this application, never merchant IDs.
    if run_id and not re.fullmatch(r"[a-f0-9]{32}", run_id):
        raise ValueError("无效日志任务编号")
    value = (datetime.now(CN).isoformat(timespec="seconds"), level, run_id,
             safe_text(stage), safe_text(message), safe_text(code))
    with closing(database(root)) as conn, conn:
        conn.execute("INSERT INTO logs(timestamp,level,run_id,stage,message,code) VALUES(?,?,?,?,?,?)", value)


def read_logs(root, *, errors_only=False, keyword="", limit=500):
    clauses, args = [], []
    if errors_only:
        clauses.append("level='ERROR'")
    if keyword.strip():
        clauses.append("instr(lower(stage || ' ' || message || ' ' || code || ' ' || run_id),lower(?))>0")
        args.append(keyword.strip())
    where = " WHERE " + " AND ".join(clauses) if clauses else ""
    args.append(max(1, min(int(limit), 10000)))
    with closing(database(root)) as conn:
        rows = conn.execute("SELECT * FROM logs" + where + " ORDER BY id DESC LIMIT ?", args).fetchall()
    return [dict(row) for row in reversed(rows)]


def format_logs(rows):
    return "\n".join(f"{r['timestamp']} [{LEVELS[r['level']]}] [{r['stage']}] {r['message']}"
                     + (f" | 错误码: {r['code']}" if r['code'] else "")
                     + (f" | 任务: {r['run_id']}" if r['run_id'] else "") for r in rows)


def exception_location(exc):
    """Type and code location only: no exception message, source or locals."""
    frames = traceback.extract_tb(exc.__traceback__)[-5:]
    return safe_text(type(exc).__name__ + "；代码位置：" + " ← ".join(
        f"{Path(f.filename).name}:{f.lineno} ({f.name})" for f in frames))


def diagnostic_report(root, *, errors_only=False, keyword=""):
    import PySide6
    rows = read_logs(root, errors_only=errors_only, keyword=keyword, limit=2000)
    return ("每日开票巡检 · 本地诊断日志\n"
            f"生成时间：{datetime.now(CN).isoformat(timespec='seconds')}\n"
            f"环境：{platform.system()} {platform.release()} / Python {platform.python_version()} / PySide6 {PySide6.__version__}\n"
            f"范围：最近最多 2000 条符合当前筛选的日志，共 {len(rows)} 条；错误筛选：{'是' if errors_only else '否'}\n"
            "仅包含程序阶段、错误码与安全代码位置，不包含原始页面、密码、验证码或买家资料。\n"
            "旧版检查记录仍保留，但没有补造旧版详细日志。\n\n" + format_logs(rows) + "\n")


def export_report(root, **filters):
    folder = Path(root) / "diagnostics"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"巡检诊断-{datetime.now(CN):%Y%m%d-%H%M%S}-{uuid.uuid4().hex[:8]}.txt"
    with path.open("x", encoding="utf-8-sig") as stream:
        stream.write(diagnostic_report(root, **filters))
    return path
