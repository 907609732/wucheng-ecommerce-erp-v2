def _write(path, cols, rows, title):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = title
    ws.append(cols)
    fill = PatternFill("solid", fgColor="1F4E79")
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = fill
    for r in rows:
        ws.append(r)
    for i, col in enumerate(cols, 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = max(12, min(30, len(col) * 2 + 4))
    ws.freeze_panes = "A2"
    wb.save(path)
    print("  生成", path)


